let names: Intl.DisplayNames | null | undefined;

/** "Japan" for 392. Null when the code isn't known. */
export function countryName(code: number | null | undefined): string | null {
  const alpha2 = code == null ? undefined : ALPHA2[code];
  if (!alpha2) return null;
  if (names === undefined) {
    try {
      names = new Intl.DisplayNames(['en-GB'], { type: 'region' });
    } catch {
      names = null;
    }
  }
  return names?.of(alpha2) ?? null;
}
